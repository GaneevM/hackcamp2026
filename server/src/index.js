import "dotenv/config";
import express from "express";
import { reportRequestSchema } from "./validate-session.js";
import { generateReport } from "./generate-report.js";

const app = express();
const port = Number(process.env.PORT || 3001);
const reportMode = process.env.REPORT_MODE || "mock";

if (!["mock", "gemini"].includes(reportMode)) {
  throw new Error("REPORT_MODE must be mock or gemini.");
}

app.use(express.json({ limit: "100kb" }));

app.get("/health", (req, res) => {
  res.json({
    status: "ok",
    service: "Motion report backend",
    reportMode
  });
});

app.post("/api/reports", async (req, res) => {
  const result = reportRequestSchema.safeParse(req.body);

  if (!result.success) {
    return res.status(400).json({
      error: "Invalid session data",
      details: result.error.issues.map((issue) => ({
        field: issue.path.join("."),
        message: issue.message
      }))
    });
  }

  const data = result.data;

  const completedReps = data.sessions.reduce(
    (total, session) => total + session.completedReps,
    0
  );

  const facts = {
    exerciseId: data.exerciseId,
    side: data.side,
    sessionCount: data.sessions.length,
    completedReps
  };

  if (reportMode === "mock") {
    return res.json({
      mode: "mock",
      dataSource: data.dataSource,
      facts,
      narrative: {
        summary:
          `Across ${data.sessions.length} synthetic session(s), ` +
          `${completedReps} completed repetitions were recorded.`,
        observations: [],
        limitations: [
          "Fictional demonstration data.",
          "This mock report was not generated by Gemini.",
          "Camera angle estimates are not clinically validated."
        ],
        questionsForReview: []
      }
    });
  }

  try {
    const narrative = await generateReport(data);

    return res.json({
      mode: "gemini",
      dataSource: data.dataSource,
      facts,
      narrative
    });
  } catch (err) {
    // Log only a short classification, not API request details.
    console.error("Report generation failed:", err.name);

    return res.status(502).json({
      error: "AI report generation failed.",
      message:
        "Your statistics are included below. " +
        "Check the API configuration and quota before retrying.",
      facts
    });
  }
});

app.use((err, req, res, next) => {
  if (err.type === "entity.parse.failed") {
    return res.status(400).json({
      error: "Request body must contain valid JSON."
    });
  }

  if (err.type === "entity.too.large") {
    return res.status(413).json({
      error: "Request body is too large."
    });
  }

  console.error("Request failed:", err.name);

  return res.status(500).json({
    error: "An unexpected server error occurred."
  });
});

app.listen(port, "127.0.0.1", () => {
  console.log(`Backend running at http://localhost:${port}`);
  console.log(`Report mode: ${reportMode}`);
});