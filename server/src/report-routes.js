import { Router } from "express";
import { reportRequestSchema } from "./validate-session.js";
import { generateReport } from "./generate-report.js";
import { saveSessions } from "./session-store.js";
import { saveReport, getReport } from "./report-store.js";
import { collectReportContext } from "./report-context.js";

export function createReportRouter(db, reportMode) {
  const router = Router();

  router.post("/", async (req, res, next) => {
    const result = reportRequestSchema.safeParse(req.body);

    if (!result.success) {
      return res.status(400).json({
        error: "Invalid session data",
        details: result.error.issues.map((issue) => ({
          field: issue.path.join("."),
          message: issue.message
        }))
      });
    }

    const data = result.data;
    const model = process.env.GEMINI_MODEL?.trim();

    if (reportMode === "gemini" && !model) {
      return res.status(500).json({
        error: "GEMINI_MODEL must be configured."
      });
    }

    let context;

    try {
      saveSessions(db, data);

      context = collectReportContext(
        db,
        data.sessions.map((session) => session.sessionId)
      );
    } catch (error) {
      if (error.status === 400 || error.status === 409) {
        return res.status(error.status).json({
          error: error.message
        });
      }

      return next(error);
    }

    let narrative;

    if (reportMode === "mock") {
      const completedReps = data.sessions.reduce(
        (total, session) => total + session.completedReps,
        0
      );

      narrative = {
        summary:
          `Across ${data.sessions.length} synthetic session(s), ` +
          `${completedReps} completed repetitions were recorded.`,
        observations: context.map(
          (item) =>
            `For session ${item.sessionId}, the user reported: ` +
            JSON.stringify(item.answer)
        ),
        limitations: [
          "Fictional demonstration data.",
          "This mock report was not generated by Gemini.",
          "Camera angle estimates are not clinically validated.",
          "User-reported context is not independently verified."
        ],
        questionsForReview: []
      };
    } else {
      try {
        narrative = await generateReport(data, context);
      } catch (error) {
        console.error("Report generation failed:", error.name);

        return res.status(502).json({
          error: "AI report generation failed.",
          message: "Session statistics were saved. No report was created.",
          sessionIds: data.sessions.map((session) => session.sessionId)
        });
      }
    }

    try {
      const saved = saveReport(
        db,
        data,
        { mode: reportMode, narrative },
        reportMode === "gemini" ? model : null,
        context
      );

      return res.status(201).json(saved);
    } catch (error) {
      return next(error);
    }
  });

  router.get("/", (req, res) => {
    const reports = db.prepare(`
      SELECT report_id, mode, model, created_at
      FROM reports
      ORDER BY created_at DESC, report_id ASC
      LIMIT 50
    `).all();

    return res.json({
      reports: reports.map((row) => ({
        reportId: row.report_id,
        mode: row.mode,
        model: row.model,
        createdAt: row.created_at
      }))
    });
  });

  router.get("/:reportId", (req, res) => {
    const report = getReport(db, req.params.reportId);

    if (!report) {
      return res.status(404).json({
        error: "Report not found."
      });
    }

    return res.json(report);
  });

  return router;
}